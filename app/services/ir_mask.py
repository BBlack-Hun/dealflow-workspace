"""이름을 가리는 **단 하나의** 자리.

## 왜 한 곳인가

가리는 규칙이 두 군데 적히면 한쪽이 낡는다. 그리고 **낡은 쪽이 이름을 그대로
내보낸다** — 가리기는 안 하는 것보다 어설프게 하는 쪽이 나쁘다. 화면·발송·
엑셀이 전부 여기를 부른다.

## 규칙

- 회사명: **첫 글자 하나**만 남기고 나머지는 별표.
- 사람 이름: **성(첫 글자)**만 남기고 나머지는 별표.

## 별표 개수는 고정이다 — 원래 길이에 맞추지 않는다

길이에 맞추면 길이가 샌다. 실측으로 확인된 것이다: 이름 242개를 첫 글자 +
`원래 길이만큼의 별표` 로 가리면 그중 **185개(76%)** 가 다른 후보가 없어
한 사람으로 확정된다. 별표를 고정하면 52개(22%)로 준다. 세 글자 이름과 다섯
글자 이름이 화면에서 **똑같이** 보여야 한다.

## 두 글자 성(남궁·선우)은 어떻게 하나

**한 글자만 남긴다.** `남궁민수` → `남***`.

복성인지 아닌지는 이름 사전 없이는 못 가른다(`남궁민` 은 성이 `남궁` 일 수도
`남` 일 수도 있다). 틀리면 두 글자가 새는 쪽으로 틀리므로, 판별하지 않고 늘
한 글자만 남긴다. 성을 덜 남기는 것은 가리기가 더 세지는 쪽이라 안전하다.

## 영문 이름

영문도 **첫 글자 하나**다. `John Smith` → `J***`, `Acme Ventures` → `A***`.
영문은 성이 뒤에 오지만, 여기서 규칙을 갈래로 나누면 어느 갈래를 탔는지가
곧 힌트가 된다 — 한 규칙으로 둔다.

## 투자사 이름은 **꼬리말만 드러낸다** — `mask_firm`

사용자가 정했다: `파트너스` · `인베스트먼트` · `자산운용` 같은 **뒷말은 보이게**.
가려진 목록이 `가*** 나*** 다***` 뿐이라 대표가 읽어도 어떤 성격의 돈이
물어봤는지를 알 수 없었기 때문이다(VC 인지 자산운용인지가 다음 연락을 정한다).

**이것은 일부러 덜 가리는 변경이다.** 위 규칙과 어긋나 보이므로 까닭을 적어 둔다.

1. **드러나는 것이 한 사람이 아니라 업종이다.** 꼬리말은 수십 곳이 함께 쓰는
   말이라 그 자체로는 아무도 집어내지 못한다. 사람 이름(`mask_person`)에는
   이런 말이 없어서 **그쪽은 그대로 첫 글자 하나**다.
2. **앞은 그대로 한 글자다.** 남기는 글자를 늘리지 않았고, 별표도 그대로
   고정이다 — 길이는 여전히 안 샌다.
3. **끝에 붙은 것만** 뗀다. 이름 한가운데 든 말은 건드리지 않는다.

### 그래도 덜 가려진다 — 잰 값 (개발 자료, 2026-09)

고유 투자사 308곳으로 재었다(위 242명과 **같은 방식**이다 — 가린 값이 그 하나
뿐인 곳을 센다).

- 지금까지(첫 글자 + 별표): **24%** 가 한 곳으로 확정된다.
- 꼬리말을 드러내면: **41%**.
- `벤처스` · `캐피탈` 까지 넓히면 47%, `증권` · `에쿼티` 까지 넓히면 55%.

그래서 **사용자가 든 셋(과 그 표기 차이)만** 둔다. 넓힐수록 확정 비율이
오르므로, 꼬리말을 더 넣는 일은 이 숫자를 다시 재고 사용자가 정할 일이다.

### 이름이 통째로 꼬리말이면 — **꼬리말도 가린다**

`파트너스` 한 낱말이 곧 이름이면 꼬리말을 드러내는 순간 이름 전부가 드러난다.
그때는 옛 규칙 그대로 `파***` 다(앞에 남는 글자가 없으면 떼지 않는다).

### 꼬리말 앞의 빈칸은 버린다

`샘플 파트너스` 도 `샘플파트너스` 도 `샘***파트너스` 로 나온다. 빈칸이 있었는지
없었는지도 이름의 생김새라 그대로 실으면 힌트가 하나 더 붙는다 — 모든 줄이
**같은 모양**이어야 한다는 별표 고정과 같은 까닭이다.

## 한 글자짜리 이름

한 글자 이름은 규칙상 통째로 남는다(`김` → `김***`). 남길 첫 글자가 곧 이름
전부라 이 규칙으로는 가릴 수가 없다 — 규칙의 한계로 적어 둔다.
"""
from __future__ import annotations

from typing import Optional

from .sheet_import import normalize_company_name, norm

# 남기는 별표. **길이와 무관하게 늘 이만큼**이다(위 설명 참고).
STARS = "***"

# 가릴 이름 자체가 없을 때. 첫 글자가 없으므로 별표만 남는다 —
# `(이름 없음)` 같은 말을 여기서 지어내면 문서마다 다른 말이 뜬다.
BLANK = STARS


def _head(value: Optional[str]) -> str:
    """가리고 남길 **첫 글자 하나**. 없으면 빈 문자열."""
    text = norm(value or "")
    return text[0] if text else ""


def mask_company(name: Optional[str]) -> str:
    """회사명 → `첫 글자 + 고정 별표`.

    `(주)`·`㈜` 같은 법인 표기는 먼저 떼고 첫 글자를 잡는다. 안 떼면 `(주)샘플가`
    가 `(***` 이 되어 남긴 한 글자가 이름의 첫 글자가 아니게 된다 — 가리는 세기는
    그대로인데 읽는 사람만 헷갈린다. 떼는 규칙은 이미 있는 것을 그대로 쓴다
    (`sheet_import.normalize_company_name`).
    """
    head = _head(normalize_company_name(name or ""))
    return f"{head}{STARS}" if head else BLANK


# 투자사 이름 **끝**에 붙는 꼬리말. 여기 있는 말만 드러난다(위 설명 참고).
#
# **사용자가 든 것은 셋이다** — `파트너스` · `인베스트먼트` · `자산운용`.
# 나머지 셋은 **같은 말의 다른 표기**일 뿐 새로 넓힌 것이 아니다:
# `자산운영`(사용자가 쓴 표기) · `파트너즈`(ㅈ) · `자산운용사`.
# 개발 자료에는 이 세 표기가 한 건도 없었지만, 한쪽만 받으면 들어오는 날
# **조용히 안 걸린다** — 안 걸려도 아무 화면에도 안 뜨는 종류의 고장이다.
#
# `벤처스` · `캐피탈` · `증권` 은 **일부러 뺐다**(개발 자료에서 각각 13 · 8 ·
# 16곳). 넣으면 한 곳으로 확정되는 비율이 41% → 47% → 55% 로 오른다.
#
# 투자사 유형을 알아내는 낱말 목록(`services/firm_type.py`)과는 **다른 일**이다.
# 저쪽은 이름 어디에 있든 찾아서 유형을 정하고, 여기는 **끝에 붙은 것만** 떼어
# 내보낸다. 저 목록을 여기서 그대로 쓰면 `사모` · `엔젤` 처럼 훨씬 좁은 말까지
# 드러나 확정 비율이 뛴다.
FIRM_SUFFIXES = ("인베스트먼트", "자산운용사", "자산운용", "자산운영",
                 "파트너스", "파트너즈")

# 긴 것부터 본다 — `자산운용사` 가 `자산운용` 보다 먼저 걸려야 `사` 한 글자가
# 앞쪽에 남지 않는다.
_SUFFIXES = tuple(sorted(FIRM_SUFFIXES, key=len, reverse=True))


def firm_suffix(name: Optional[str]) -> str:
    """이름 **끝**에 붙은 꼬리말. 없으면 빈 문자열.

    - **끝에 있을 때만**이다. `파트너스자산운용` 은 `자산운용` 만 떼고
      가운데 `파트너스` 는 가려진 쪽에 남는다. 가운데까지 드러내면 남는 글자가
      한 글자뿐인 이름이 생긴다.
    - **앞이 남지 않으면 꼬리말이 아니다.** 이름이 통째로 `파트너스` 면 빈
      문자열을 돌려주어 옛 규칙(`파***`)으로 떨어진다.
    """
    text = norm(name or "")
    for suffix in _SUFFIXES:
        if text.endswith(suffix) and text[:-len(suffix)].strip():
            return suffix
    return ""


def mask_firm(name: Optional[str]) -> str:
    """**투자사** 이름 → `첫 글자 + 고정 별표 + 꼬리말`.

    `샘플파트너스` → `샘***파트너스`, `샘플 파트너스` → `샘***파트너스`,
    꼬리말이 없으면 `mask_company` 그대로 `샘***`.

    회사명 일반(`mask_company`)과 **갈래를 나눈 까닭**: 꼬리말 목록은 투자사
    이름의 말이다. `mask_company` 를 통째로 바꾸면 그 함수를 부르는 모든 자리
    (지금은 투자사뿐이지만 화면·발송·엑셀이 다 여기를 부른다)가 같이 바뀌어,
    **스타트업 기업명**을 가리는 날 투자사용 규칙이 따라간다.

    갈래를 나눠도 **가리는 규칙이 두 군데 적히지는 않는다** — 별표를 붙이는
    일도, 남길 첫 글자를 고르는 일도 아래 `mask_company` 하나가 한다. 이 함수가
    더하는 것은 **꼬리말을 떼어 두었다가 뒤에 도로 붙이는 것**뿐이다.
    """
    text = norm(normalize_company_name(name or ""))
    suffix = firm_suffix(text)
    if not suffix:
        return mask_company(text)
    return f"{mask_company(text[:-len(suffix)])}{suffix}"


def mask_person(name: Optional[str]) -> str:
    """사람 이름 → `성(첫 글자) + 고정 별표`.

    회사명과 **같은 모양**으로 나온다. 모양이 다르면 그 차이가 곧 어느 쪽 값인지를
    말해 주고, 문서에 둘이 나란히 서면 길이 힌트와 같은 일을 한다.
    """
    head = _head(name)
    return f"{head}{STARS}" if head else BLANK
