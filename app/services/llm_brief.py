# `V-031` · `v-31` · `C - 7` 을 모두 같은 번호로 읽는다.
#
# **자릿수를 채우지 않는다.** `V-031` 로 내보내면 번호가 1000 을 넘는 순간
# 같은 사람을 가리키는 표기가 둘이 된다(`V-031` 과 `V-1000` 은 폭이 다르다).
# 대신 **읽을 때 앞의 0 을 버려서** 어느 쪽으로 답해 와도 찾아 준다.
#
# **맨숫자(`31`)는 일부러 안 받는다.** 답에는 `30억` · `3곳` · `2026년` 처럼
# 번호가 아닌 숫자가 널려 있다. 그것까지 번호로 읽으면 엉뚱한 사람이 목록에
# 뜨고, 그 목록은 겉보기에 멀쩡하다 — 틀린 것을 알아채기 어려운 쪽이 나쁘다.
_REF = re.compile(rf"(?<![0-9A-Za-z])([{INVESTOR_PREFIX}{COMPANY_PREFIX}])"
                  r"\s*-\s*0*(\d+)", re.IGNORECASE)


def parse_refs(text: str) -> Dict[str, List[int]]:
    """붙여 넣은 글에서 번호만 골라낸다 — `{"investors": [...], "companies": [...]}`.

    사람은 LLM 의 답을 **통째로** 붙여 넣는다("V-031 님께 C-7, C-12 를 …").
    번호만 뽑아 달라고 하면 손으로 옮겨 적다 틀린다. 순서는 나온 순서대로
    두되 같은 번호는 한 번만 담는다 — 한 답 안에서 같은 사람이 여러 번
    거론되는 것은 흔한 일이고, 그때마다 줄이 늘면 읽기 어렵다.
    """
    found: Dict[str, List[int]] = {"investors": [], "companies": []}
    for prefix, digits in _REF.findall(text or ""):
        key = "investors" if prefix.upper() == INVESTOR_PREFIX else "companies"
        number = int(digits)
        if number and number not in found[key]:
            found[key].append(number)
    return found


#: 줄머리에서 떼어 내는 글머리표·번호 매김. 사람이 붙여 넣는 답은 목록 모양으로
#: 오는 일이 흔하다(`- 공통: …` · `**공통**: …` · `1. 공통: …`) — 떼지 않으면
#: 갈래 이름이 줄머리에 없는 것으로 읽혀 그 줄이 통째로 어느 갈래에도 안 붙는다.
_LINE_HEAD = re.compile(r"^[\s\-*#>·••●]*(?:\d+[.)]\s*)?[\s*_]*")

#: 갈래 이름 뒤에 올 수 있는 **쌍점**. 전각(`：`)으로 적혀 오는 일이 실제로 있다.
_HEAD_SEPS = (":", "：")


def parse_group_refs(text: str, group_names) -> List[dict]:
    """갈래별로 적혀 온 답을 **갈래마다의 기업 번호**로 가른다.

    `[{"name": "공통", "companies": [7, 12]}, …]` — 답에 나온 순서대로.

    ## 왜 필요한가

    딜 소개가 **그룹 단위로 나가게 되면서**(`prompt` 참고) 답도 갈래마다 한
    줄씩 온다. `parse_refs` 는 글 전체에서 번호만 훑으므로, 그대로 쓰면 아홉
    갈래의 답이 **한 덩어리로 뭉개진다** — 사람이 그것을 다시 갈래로 갈라야
    하고, 갈래가 아홉이면 아홉 번이다. 갈라 주는 자리가 여기다.

    ## 갈래 이름을 **지어내지 않는다**

    줄머리를 아무 말이나 갈래 이름으로 읽지 않고, **앱이 실제로 쓰는 이름**
    (`sheet_owner.group_rows` 의 `label`)에만 붙인다. 지어내면 답에 적힌 소제목
    (`후보`·`제외`)이 갈래가 되어 화면에 없는 갈래가 뜬다.

    **긴 이름부터 맞춰 본다.** `Series C` 와 `Series C 이상` 이 둘 다 있으면
    짧은 쪽이 먼저 걸려 긴 쪽이 영영 안 잡힌다.

    ## 줄머리에 있어야 갈래다

    `... 공통: C-7` 처럼 문장 가운데 있는 것은 갈래 머리가 아니다. 그리고 이름과
    쌍점 사이에 **번호가 없어야** 한다 — `C-7, 공통: …` 같은 줄을 갈래 머리로
    읽으면 앞의 번호를 엉뚱한 갈래에 붙이게 된다.

    ## 머리가 나오기 전의 번호는 **어느 갈래도 아니다**

    답 첫머리의 요약 문장에 번호가 섞여 있는 일이 흔하다. 그것을 첫 갈래에
    붙이면 그 갈래가 고르지도 않은 기업을 받는다 — 버리지 않고 그냥 갈래에
    안 넣는다(`resolve` 가 전체 목록에는 그대로 싣는다).

    같은 갈래가 두 번 나오면 **한 갈래로 합친다.** 갈래 안에서 같은 번호는 한
    번만 담되, **갈래끼리는 겹쳐도 그대로 둔다** — 겹치는 것을 허용한 것이
    시킬 말이다(`prompt`).
    """
    named = {(g or "").strip() for g in (group_names or [])}
    labels = sorted((n for n in named if n), key=len, reverse=True)
    picks: Dict[str, List[int]] = {}
    order: List[str] = []
    current: Optional[str] = None
    for line in (text or "").splitlines():
        head = _LINE_HEAD.sub("", line)
        for label in labels:
            if not head.startswith(label):
                continue
            rest = head[len(label):]
            # 이름이 **거기서 끝나야** 갈래다. `A` 로 `AI 분야:` 를 잡으면 한
            # 글자짜리 갈래(`A`·`B`·`E` 가 실제로 있다)가 아무 줄에나 붙는다.
            if rest[:1].isalnum():
                continue
            cut = min((rest.index(s) for s in _HEAD_SEPS if s in rest),
                      default=-1)
            if cut < 0 or _REF.search(rest[:cut]):
                continue
            current = label
            if label not in picks:
                picks[label] = []
                order.append(label)
            line = rest[cut + 1:]
            break
        if current is None:
            continue
        for prefix, digits in _REF.findall(line):
            if prefix.upper() != COMPANY_PREFIX:
                continue
            number = int(digits)
            if number and number not in picks[current]:
                picks[current].append(number)
    return [{"name": name, "companies": picks[name]} for name in order]


