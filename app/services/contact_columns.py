@dataclass(frozen=True)
class Column:
    """표의 칸 하나. 머리글·폭·고치는 방식이 여기서 한 번에 정해진다."""

    label: str                  # 머리글 — **원본 시트 그대로**
    key: str                    # 행이 싣는 이름 (field 면 모델 칸, note 면 notes 키)
    width: int                  # px. 값 길이에 맞춘다(머리글 길이가 아니라)
    # field | note | row_no | actions | stamp
    #
    # `stamp` — **앱이 적고 사람은 못 고치는 값**(`수정한 날짜`). 행이 그 키로
    # 실어 둔 글자를 그대로 그린다. 다른 갈래와 갈라 두는 이유는 하나다:
    # 사람이 고칠 수 있으면 "언제 고쳤나" 가 곧 거짓이 된다. 그래서 이 갈래는
    # 표에서 `class="cell"` 도 `data-field` 도 안 받고(눌러도 아무 일이 없다)
    # 수정창에도 안 선다(`panel_columns`). IR 기업 현황의 같은 칸이 먼저
    # 그렇게 섰다(#200) — 저쪽은 표가 화면에 그대로 적혀 있어 갈래가 필요
    # 없었고, 이쪽은 표가 이 목록에서 나오므로 갈래로 적는다.
    source: str = "field"
    kind: str = "text"          # text | long | pick | email — 어떻게 고치나
    choices: str = ""           # pick 일 때 정해진 보기 (`O,X`)
    hint: str = ""              # 수정창의 placeholder. **이름이 아니다**
    in_table: bool = True       # 표에 세울까 (False = 수정창에서만)

    @property
    def filterable(self) -> bool:
        """이 칸에 머리글 필터를 다는가 — **고를 수 있는 칸인가**로 정한다.

        판정을 `choices`(미리 적어 둔 보기)로 하지 않는다. 보기 목록은 "지금
        정해 둔 값이 있느냐" 이고, 필터가 필요한지는 "이 칸이 **고르는 칸이냐**"
        가 정한다. 둘은 지금 표에 선 칸에서만 우연히 겹친다 — 보기를 안 적고
        `pick` 으로 둔 칸이 셋 있고(`사업분야 대분류`·`소분류`·`기업구분`),
        그 칸들은 수정창에서 **이미 다른 줄이 쓰고 있는 값을 모아** 고르게 한다
        (`static/js/inline_edit.js` 의 `startPick`). 고르는 칸인데 필터만 조용히
        빠지는 것이 정확히 이 저장소가 반복해 당한 부류다.

        **자유롭게 적는 칸에는 안 단다.** `text`(이름·연락처)와 `long`(메모·
        한줄 소개)은 줄마다 값이 달라서, 필터를 열면 줄 수만큼 항목이 생긴다 —
        고를 것이 없는 목록이라 자리만 먹는다.

        `email` 도 같다. 그 칸이 후보를 띄우기는 하지만 띄우는 것은 **`@` 뒤
        도메인**뿐이고(`static/js/email_hint.js`), 값 자체는 줄마다 다르다 —
        `pick` 과 달리 필터를 걸 것이 없다.
        """
        return self.kind == "pick"


@dataclass(frozen=True)
class Layout:
    """한 명단이 쓰는 칸 묶음 — 그리고 그 명단이 **어느 화면에 사는가**."""

    key: str
    label: str
    # 이 배치를 쓰는 명단이 뜨는 화면. 주소 조각과 같다(`contacts` · `startup`),
    # `RefSheet.page` 와 같은 값이고 같은 뜻이다.
    #
    # **왜 배치가 화면을 정하나.** 명단이 어느 화면에 사는지는 새 칸(`SheetOwner.
    # page`)으로도 둘 수 있었다. 두지 않은 이유는 그러면 명단마다 값이 **둘**이
    # 되기 때문이다 — 새 명단을 넣는 사람이 배치만 맞추고 화면을 빠뜨리면,
    # 스타트업 칸을 쓰는 명단이 투자사 관리 현황에 서거나 그 반대가 된다.
    # 화면은 멀쩡하고 아무도 눈치채지 못하는 부류다(이 저장소가 반복해 당했다).
    #
    # 배치는 이미 **그 명단이 어떤 명단인지**를 가리킨다. `startup` 배치의 이름은
    # `스타트업 리마인드` 이고 머리글이 `기업명`·`성함` 이며 투자사로 세지 않는다
    # — 아래 `INVESTOR_MONTHLY_LAYOUT` 주석이 저 배치를 돌려 쓰지 않은 이유로
    # 바로 그것을 든다. 그래서 값을 하나 더 두지 않고 배치에 붙인다.
    #
    # 사람이 화면에서 켜고 끄는 값(`SheetOwner.is_hidden`)으로 가르지 않는 이유도
    # 같다 — 그 단추 한 번에 명단이 화면을 옮겨 다니면 어디서 고쳐야 할지 모른다.
    page: str = "contacts"
    # 월별 칸 **앞**에 서는 고정 칸들
    head: List[Column] = field(default_factory=list)
    # 월별 칸 **뒤**에 서는 고정 칸들
    tail: List[Column] = field(default_factory=list)
    # 표에는 안 세우고 수정창에서만 보는 칸들
    extra: List[Column] = field(default_factory=list)
    # 표 **왼쪽에서 이만큼의 칸**은 가로로 밀어도 제자리에 선다.
    #
    # ## 왜 필요한가
    #
    # 이 표들은 화면보다 1,900px 넘게 넓다(스타트업 리마인드는 달이 쌓일수록 더
    # 넓어진다). 머리행은 이미 세로 스크롤에 고정돼 있는데(`app.css` 의
    # `thead th { position: sticky; top: 0 }`) 첫 열은 아니어서, 오른쪽 끝의
    # 9월 칸을 보는 동안 **어느 기업 줄인지 알 수가 없었다.** 사용자가 든 말이
    # 그것이다 — "첫 행은 고정인데 왜 좌우 스크롤이 되면 스타트업 이름은 고정이
    # 또 아닌지, 일관된 UX 규칙이 없는 것 같습니다."
    #
    # ## 왜 하필 두 칸인가
    #
    # `NO` 와 **그다음 한 칸**이다. 그다음 한 칸은 이 명단의 주인공 이름이다 —
    # 기업이 주인공인 배치는 `기업명`, 사람이 주인공인 배치는 `이름`
    # (`firm_leads` 가 읽는 바로 그 차례다). `NO` 만 고정하면 번호만 남아 어느
    # 기업인지 여전히 모르고, 한 칸 더 고정하면(`성함`·`연락처`) 고정 폭이
    # 300px 을 넘어 정작 밀어서 볼 자리가 줄어든다.
    #
    # 이 값은 **개수**지 px 이 아니다. 실제 왼쪽 자리는 화면이 칸 폭을 더해서
    # 낸다(`contacts.html`) — 여기에 px 을 적어 두면 칸 폭을 고칠 때마다 두
    # 군데를 맞춰야 하고, 한쪽만 고쳐지는 날 고정된 칸이 반 칸씩 어긋난다.
    #
    # 투자사 명함 표는 `head` 가 비어 있지만(머리글이 화면에 그대로 적혀 있다)
    # **같은 규칙을 그 화면에도 손으로 적어 두었다** — 두 표가 다르게 굴면
    # "일관된 UX 규칙이 없다" 는 그 불만이 그대로 남는다.
    sticky: int = 2
    # 달마다 늘어나는 칸을 쓰는 배치인가
    monthly: bool = False
    # 달마다 늘어나는 칸을 **어떻게 고치고 보여 주나.**
    #
    # 지금은 세 배치가 다 `long`(여러 줄 메모)이다. 그래도 **배치마다 정하는
    # 값으로 남긴다** — 값의 성격이 배치마다 다르다는 것이 이 표들의 사실이고
    # (투자사 딜공유는 한 칸에 회차별 기업 목록이 400자 넘게 쌓이고, 스타트업
    # 리마인드는 그 달에 무엇을 하고 무슨 말을 들었는지를 2~3줄로 적는다),
    # 고정하면 다음에 성격이 다른 명단이 들어올 때 화면에 `if` 를 심게 된다.
    #
    # 칸마다가 아니라 **배치마다** 정하는 이유: `ContactColumn` 에 종류를 두면
    # 마이그레이션이 필요하고, 같은 명단 안에서 칸마다 성격이 갈릴 일은 없다
    # (한 시트의 월별 칸은 다 같은 모양이다).
    #
    # **기본값을 `long`·`""` 으로 둔다.** 한동안 `pick`·`O,X` 였는데, 그때는
    # 배치를 안 적은 명단의 월별 칸이 고르는 칸으로 서서 **한 번 고치는 순간
    # 그 달에 적어 둔 글이 한 글자로 덮였다.** 모르는 명단에서는 덮지 않는
    # 쪽이 맞다.
    month_kind: str = "long"
    month_choices: str = ""
    month_width: int = 240
    # 달 이름이 붙은 칸이 **하나도 없는** 명단에 처음 세울 칸들. 달은 빼고
    # 뒷말만 적는다(`리마인드 문자` → `8월 리마인드 문자`).
    #
    # **왜 필요한가.** 달마다 늘어나는 칸은 그 표의 가장 최근 달 칸을 본떠
    # 만든다(`services/monthly_columns.py`) — 이름을 짓는 것이 코드가 아니라
    # 그 표를 쓰던 사람이게 하려는 것이다. 그래서 본이 없는 명단은 비켜 갔고,
    # 담당자별 스타트업 명단 중 **한 명의 것만** 달 칸이 서 왔다. 나머지는
    # 사람이 첫 칸을 손으로 심어 줘야 자동 생성이 붙는데, 심는 것을 잊은 명단만
    # 조용히 그 달 기록이 지난 칸에 섞여 들어간다.
    #
    # **명단 이름이 아니라 배치에 적는다.** "달 칸이 서 있는 그 명단에서 본떠
    # 온다" 로 하면 코드가 사람 이름·명단 이름을 알아야 하고(이 저장소가 값으로
    # 빼 둔 바로 그것 — `SheetOwner.layout` 주석), 본이 된 명단에서 누가 칸
    # 이름을 고치는 순간 **남의 명단에 생길 칸 이름이 같이 바뀐다.** 이 세 칸은 팀이
    # 함께 쓰는 한 가지 모양이라(담당자별 스타트업 워크북이 한 틀에서 나온다 —
    # `scripts/import_startup_sheet.py` 의 `NOTES` 주석) 배치의 성질이 맞다.
    #
    # 비어 있으면 지금까지 그대로다 — 본이 없는 표에는 아무것도 만들지 않는다.
    # 달을 안 쓰는 표에 달 칸이 생기면 그 표를 쓰던 사람이 지워야 한다.
    month_seed: tuple = ()
    # 월별 칸 머리글 **뒤에 붙여 보여 주는 말**(`(내용 기입)`). 저장된 이름은
    # 그대로다 — 붙이는 것은 그리는 자리뿐이다(`as_column`).
    #
    # ## 왜 저장된 이름을 안 고치나
    #
    # 월별 칸 이름은 **시트 머리글 그대로**이고, 시트를 다시 올릴 때 임포터가
    # 그 글자로 칸을 찾는다(`scripts/import_startup_sheet.py` — `if label not
    # in columns`). 저장된 이름에 `(내용 기입)` 을 붙이면 다음 업로드에서 그
    # 칸을 못 찾아 **같은 달 칸이 두 벌** 서고, 값은 옛 칸에 남는다.
    #
    # `IR dack` → `IR Deck` 과 같은 결이다(모듈 첫머리 주석) — 화면 이름과
    # 시트 이름이 갈릴 때, 이 저장소는 **시트 쪽을 그대로 두고 화면만 고친다.**
    #
    # ## 왜 `month_seed` 에 적지 않나
    #
    # `month_seed` 는 **달 칸이 하나도 없는 명단**에만 쓰인다. 이미 칸이 선
    # 명단은 직전 달 칸을 본떠 이름을 짓기 때문에(`monthly_columns.relabel`),
    # 거기 적으면 **새 명단에만** 붙고 지금 쓰는 명단에는 영영 안 붙는다.
    # 게다가 `month_seed` 가 짓는 것은 저장되는 이름이라 위 문제를 그대로 진다.
    #
    # 여기 두면 **옛 칸도 새 칸도 같은 머리글**로 선다 — 달마다 새로 생기는
    # 칸에 사람이 손으로 붙일 자리가 없다는 뜻이기도 하다.
    month_label_suffix: str = ""
    # ── 새 줄 하나가 **반드시 갖춰야 하는 칸** ────────────────────────────
    #
    # 이 명단에서 줄 하나를 알아보는 이름이다. 투자사 명단은 **사람**이
    # 주인공이라 `이름`(`name`)이고, 스타트업 명단은 **기업**이 주인공이라
    # `기업명`(`firm`)이다 — 위 `sticky` 주석이 말하는 그 차례의 주인공과
    # 같은 칸이다.
    #
    # **배치에 둔다.** 화면이나 라우터에 `if 스타트업이면 firm` 을 심으면
    # 명단이 하나 늘 때 또 심어야 하고, 심는 것을 잊은 쪽만 조용히 이름 없는
    # 줄을 받는다 — 이름이 없는 줄은 표에서 빈칸으로 서서 어느 기업인지 알
    # 수가 없다(그리고 지우려 해도 무엇을 지우는지 확인창이 말해 주지 못한다).
    required: str = "name"
    #: 그 칸을 사람에게 부르는 말. **표 머리글이 있으면 그것을 그대로 쓴다**
    #: (아래 `required_label`) — 두 곳에 적어 두면 표는 `기업명`, 안내는
    #: `회사명` 이 되어 같은 칸인지 알아볼 수가 없다. 이 값은 머리글이 화면에
    #: 그대로 적혀 있어 목록에 없는 배치(투자사 명함)만 쓴다.
    required_fallback: str = "담당자명"

    @property
    def required_label(self) -> str:
        """반드시 있어야 하는 칸을 **표 머리글 그대로** 부른다."""
        for column in list(self.head) + list(self.tail) + list(self.extra):
            if column.source == "field" and column.key == self.required:
                return column.label
        return self.required_fallback


