from __future__ import annotations

VERSION = "0.11.2"

# 이 버전보다 낡은 발송 프로그램은 화면에서 '갱신 필요' 로 표시한다.
#
# 0.4.0 부터 **한 건을 보내기 직전마다 서버에 확인한다**
# (`GET /api/agent/jobs/{id}/state`). 그 아래는 폴링 때 받은 명단을 메모리에
# 들고 끝까지 돌아서, 화면에서 [중단]을 눌러도 카톡이 계속 나간다 — 서버가
# 결과 보고만 거부해 기록에 안 남을 뿐 받는 쪽은 그대로 받는다.
#
# 0.5.0 부터 **상한(job_cap)에 걸려 남은 건을 버리지 않는다**. 그 아래는 서버가
# 내준 97건에서 앞 60건만 처리하고 잡 전체를 완료로 보고했다.
#
# 다만 이쪽은 **서버가 이미 막는다** — 대기 건이 남았는데 완료 보고가 오면 서버가
# 잡을 다시 큐로 돌려 남은 건만 이어 보내게 한다(`routers/agent_api.py: _settle`).
# 그래서 낡은 발송 프로그램으로도 사람이 빠지지는 않는다. 갱신하면 애초에 잘릴
# 일이 없어져 회차가 한 번에 끝난다.
#
# 낡은 것을 **막지는 않는다**(위 '어떻게 쓰나' 참고). 대신 팀 화면에서 크게
# 드러내야 한다 — 이건 문구가 예쁘게 안 나가는 정도가 아니라 멈춰야 할 발송이
# 안 멈추는 문제라, 갱신 전까지는 [중단]을 믿으면 안 된다.
MIN_AGENT_VERSION = "0.5.0"


def as_tuple(value: str) -> tuple:
    """`"0.2.0"` → `(0, 2, 0)`. 비교하려고. 못 읽는 값은 (0,) 로 둔다 —
    모르는 버전은 낡은 것으로 보는 편이 안전하다."""
    parts = []
    for chunk in (value or "").split("."):
        digits = "".join(c for c in chunk if c.isdigit())
        if not digits:
            break
        parts.append(int(digits))
    return tuple(parts) or (0,)


def agent_is_old(reported: str | None) -> bool:
    """이 발송 프로그램이 갱신이 필요한가. 버전을 안 알리면 낡은 것으로 본다."""
    if not reported:
        return True
    return as_tuple(reported) < as_tuple(MIN_AGENT_VERSION)
