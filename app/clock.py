"""앱이 '지금'을 읽는 **단 하나의** 자리.

왜 한 자리인가
--------------
전에 컨테이너 시간대만 ``Asia/Seoul`` 로 고쳤다. 그런데 시각을 **저장하는**
쪽은 ``datetime.now(timezone.utc)`` 로 다섯 군데에 흩어져 있었다
(``deps`` · ``models`` · ``cadence`` · ``mail_sender`` · ``auth``). 한 군데도
고쳐지지 않은 채 남아 같은 버그가 그대로 살아남았다. 부를 곳이 하나면
다음에 또 갈라지지 않는다.

왜 UTC 로 저장하지 않는가
-------------------------
저장을 UTC 로 두는 것은 일반적으로 옳다. 하지만 이 앱은 시각을 **문자열**로
넣고, 읽는 쪽이 스무 곳 넘게 **앞 10자를 잘라 날짜로 쓴다**(``sent_at[:10]``).
그 날짜를 ``date.today()`` 와 견주고, SQL 에서도 날짜 문자열과 ``>=`` 로
비교한다(``dashboard.py`` 의 주간 발송 집계, ``readiness.py`` 의 최근 발송
확인). 한국시간 자정~오전 9시에는 UTC 날짜가 **어제**라서, 그 시간대에 보낸
발송의 후속이 하루 당겨져 잡혔다(6~7일 뒤로 잡아야 할 리마인드가 5일 뒤).

읽는 스무 곳을 전부 시간대 변환으로 감싸는 길도 있었지만, SQL 쪽은 그렇게
못 한다 — ``coalesce(sent_at,'') >= '2026-08-24'`` 를 시간대까지 아는 비교로
바꾸려면 칸마다 ``datetime(sent_at,'+9 hours')`` 를 씌워야 하고, 그러면 색인을
못 탄다. 게다가 앞으로 누가 ``[:10]`` 을 한 줄 더 쓰는 순간 다시 어긋난다.
**적는 한 곳**을 화면과 같은 날짜로 맞추는 편이 고칠 곳도 적고 새는 곳도 없다.

왜 오프셋(``+09:00``)을 남기는가
--------------------------------
떼면 **순간**(instant)을 잃는다. 세션 만료와 에이전트 연결 경과시간은
``clock.now() - fromisoformat(저장값)`` 으로 재는데, naive 와 aware 를 빼면
``TypeError`` 다. 오프셋이 붙어 있으면 앞 10자는 한국 날짜로 읽히면서 순간
계산도 그대로 맞는다. 지역시간으로 옮기면서 잃는 것이 없다.

왜 ``+09:00`` 을 코드에 박지 않는가
-----------------------------------
``astimezone()`` 은 프로세스 시간대를 따른다. 그래야
``now_iso()[:10] == date.today().isoformat()`` 이 **시간대 설정과 무관하게**
항상 성립한다 — 이 둘이 어긋난 것이 버그의 정체였으므로, 어떤 환경에서도
어긋나지 않는 쪽을 고른다. 한국 시간이라는 것은 compose 의 ``TZ`` 하나가
정하고 ``test_timezone.py`` 가 그것을 지킨다. 고칠 손잡이도 하나다.

``date.today()`` 는 왜 그대로 두는가
------------------------------------
이미 프로세스 시간대를 따르므로 처음부터 옳았다. 어긋난 쪽은 저장이었다.
여기서 저장을 지역시간으로 맞추면 둘이 같은 날을 가리킨다.
"""
from __future__ import annotations

from datetime import date, datetime


def now() -> datetime:
    """지금. 프로세스 시간대의 **오프셋이 붙은** 값이다(naive 가 아니다).

    경과시간을 잴 때 저장값(aware)과 그대로 빼려면 이쪽도 aware 여야 한다.
    """
    return datetime.now().astimezone()


def now_iso() -> str:
    """저장용 시각 문자열 — ``2026-08-27T00:21:24+09:00``.

    초까지만 적는다. 마이크로초를 쓰는 곳이 없는데 칸마다 길이가 들쭉날쭉하면
    문자열로 정렬·비교하는 자리에서 읽기만 어려워진다.
    """
    return now().isoformat(timespec="seconds")


def today() -> date:
    """오늘(지역 날짜). ``now_iso()[:10]`` 과 항상 같은 날이다."""
    return now().date()
